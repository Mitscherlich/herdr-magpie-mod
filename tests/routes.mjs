import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const js = await readFile(new URL("../mods/magpie-routing/routes.js", import.meta.url), "utf8");
const { source, seat, ok, whole, mergeTrace, staged, seats, stateOf, color, geometry, way, stableSeats, destination, speed } = await import("data:text/javascript;base64," + Buffer.from(js).toString("base64"));
const now = Date.now();
assert.equal(destination({ name: "Codex", who: "account@example.com", kind: "account" }, true), "Codex · ••••");
assert.equal(destination({ name: "Relay", who: "key name", kind: "key" }, false), "Relay · key name");
assert.equal(speed({ done: true, out: 600, ms: 4000, ttft: 1000 }), "200 tok/s");
assert.equal(speed({ done: true, out: 2000, ms: 10000, ttft: 9900, flow: 100 }), "≥200 tok/s", "burst replies must not show inflated decode speed");
assert.equal(speed({ done: true, out: 3000, reasoning: 1000, ms: 12000, ttft: 1000, firstText: 2000 }), "200 tok/s");
assert.equal(speed({ done: true, canceled: true, out: 3000, ms: 10000 }), "");
assert.equal(speed({ done: false, out: 3000, ms: 10000 }), "");
const route = (id, fields = {}) => whole({ id, agent: "codex", model: "p/m", provider: "p", done: false, time: new Date(now).toISOString(), ...fields });
const envelope = (seq, routes, ids = routes.map(r => r.id), pid = 1) => ({ object: "trace", seq, routes, ids, pid });
const state = { seq: 0, routes: new Map() };
assert(mergeTrace(state, envelope(1, [route(1)])));
assert.equal(state.routes.get(1).tries.length, 0);
assert(!mergeTrace(state, envelope(2, [route(1, { done: true })])));
mergeTrace(state, envelope(3, [route(2)], [2]));
mergeTrace(state, envelope(4, [], []));
assert(!state.routes.has(2), "trimmed live request cannot stay answering forever");
assert(state.routes.has(1), "completed recent requests stay available");
assert(mergeTrace(state, envelope(1, [route(9)], [9], 2)));
assert.deepEqual([...state.routes.keys()], [9], "owner restart resets stale requests");
assert.throws(() => mergeTrace(state, { seq: 2, routes: [] }), /Invalid/);
assert.throws(() => mergeTrace(state, envelope(2, [route(10, { tries: [null] })])), /Invalid/);
mergeTrace(state, envelope(2, Array.from({ length: 70 }, (_, i) => route(i + 100))));
assert.equal(state.routes.size, 60);
const agents = Array.from({ length: 5 }, (_, i) => route(i, { agent: "agent" + i }));
assert.equal(new Set(staged(new Map(agents.map(r => [r.id, r])), null, now).map(source)).size, 4);
const callers = [route(1, { callerKey: "a" }), route(2, { callerKey: "b" })];
assert.notEqual(source(callers[0]), source(callers[1]));
assert.deepEqual(staged(new Map(agents.map(r => [r.id, r])), agents[0], now), [agents[0]]);
const completed = [route(1, { done: true, time: new Date(now - 20000).toISOString() }), route(2, { agent: "claude", done: true })];
assert.deepEqual(staged(new Map(completed.map(r => [r.id, r])), null, now).map(r => r.id), [2]);
const w = { id: "p#key", provider: "p", model: "m", name: "Provider" }, tr = { ...w, done: false };
const r = route(3, { order: [w], left: [w, { ...w, id: "held", held: true }], tries: [tr] });
assert.equal(seats([r]).length, 1);
assert.equal(seats([r, { ...r, order: [{ ...w, used: 42 }], left: [] }])[0].used, 42, "seat keeps its position but reads the latest quota snapshot");
assert.equal(stateOf(w, [r], now).kind, "live");
assert.equal(stateOf(w, [{ ...r, contentAt: now - 16000 }], now).kind, "quiet");
assert.equal(stateOf(w, [{ ...r, done: true, canceled: true }], now).kind, "canceled");
assert.equal(stateOf(w, [{ ...r, done: true, tries: [{ ...tr, done: true, status: 200 }] }], now).kind, "done");
assert.equal(stateOf(w, [{ ...r, done: true, tries: [{ ...tr, done: true, status: 429, fail: "rate limited" }] }], now).kind, "error");
assert(!ok({ status: 0 })); assert(!ok({ status: 200, fail: "refused" }));
const given = new Map(), near = new Set();
for (const id of ["codex", "claude", "crush", "opencode"]) { const c = color(id, given, near); assert(!near.has(c)); near.add(c); }
assert.equal(given.get("codex"), "#858ad7");
for (const width of [280, 532, 560, 561, 860]) {
  const g = geometry(width, ["codex", "claude"], [w]), p = way(g, "codex", seat(w));
  assert.equal(g.width, width);
  assert(g.agents.get("codex").x + g.agents.get("codex").w < g.hub.x);
  assert(g.hub.x + g.hub.w < g.rows.get(seat(w)).x, "narrow panel never changes the three-column route topology");
  assert.equal(p.length, 1, "the reference video has no visible hub leg");
  assert.deepEqual(p[0].slice(0, 2), [g.agents.get("codex").w, g.agents.get("codex").y + 12]);
  assert.deepEqual(p[0].slice(-2), [g.rows.get(seat(w)).x, g.rows.get(seat(w)).y + 12]);
  assert.deepEqual(way(g, "codex", seat(w), "back")[0].slice(0, 2), p.at(-1).slice(-2));
  assert.equal(way(g, "codex", seat(w), "retry-back").length, 1);
  assert(g.rows.get(seat(w)).w > 0);
  assert.equal(g.rows.get(seat(w)).x + g.rows.get(seat(w)).w, width, "seats fit the compact panel without horizontal scrolling");
  assert.equal(way(g, "missing", seat(w)), null);
}
assert.deepEqual(stableSeats([{ ...r, order: [w, { ...w, id: "next" }] }], ["next\u0001m", seat(w)]).map(seat), ["next\u0001m", seat(w)]);
assert(staged(new Map(completed.map(r => [r.id, r])), null, now, new Set([1])).some(r => r.id === 1), "completed flight stays on stage until its return lands");
console.log("Routing self-check passed (trace, restart, trim, concurrent callers, states, colors, resize).");
